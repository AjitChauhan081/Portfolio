        const hero = document.getElementById('hero');
        const nav = document.getElementById('main-nav');
        
        // --- Navigation Visibility Logic ---
        if (nav && hero) { 
            const heroHeight = hero.offsetHeight;
            if (window.scrollY > heroHeight * 0.8) {
                nav.classList.remove('invisible', 'opacity-0');
                nav.classList.add('opacity-100');
            } else {
                nav.classList.add('invisible', 'opacity-0');
                nav.classList.remove('opacity-100');
            }
        }
        // ---------------------------------------------
        
        const sections = document.querySelectorAll('.section');
        let visibleSectionId = 'hero'; // Default to 'hero' if at top
        
        sections.forEach(section => {
            const rect = section.getBoundingClientRect();
            
            // Check if section is approximately centered in the viewport (50% threshold)
            const isVisible = rect.top <= window.innerHeight * 0.5 && rect.bottom >= window.innerHeight * 0.5;

            if (isVisible) {
                section.classList.add('active');
                visibleSectionId = section.id;
            } else {
                section.classList.remove('active');
            }
        });
        
        // Load particle configuration for the visible section
        loadParticlesConfig(visibleSectionId);
        
        // Synchronize the Navbar active state
        updateNavbarActiveState(visibleSectionId);
