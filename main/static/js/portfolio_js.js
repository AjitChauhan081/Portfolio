/**
 * @function loadParticlesConfig
 * Loads the particles.js configuration for a given section, handling cleanup and background change.
 */
function loadParticlesConfig(configName) {
    const configData = particleConfigs[configName] || particleConfigs.hero;
    
    // Change Body Background Color Smoothly
    if (configData.bgColor) {
        document.body.style.transition = 'background-color 1.0s ease';
        document.body.style.backgroundColor = configData.bgColor;
    }

    // CRITICAL FIX: Execute cleanup and load if the section has changed
    if (configName !== currentParticleConfig) {
        
        // 1. GUARANTEED CLEANUP: Explicitly remove the old canvas element. 
        const container = document.getElementById(PARTICLE_CONTAINER_ID);
        const canvas = container ? container.querySelector('canvas') : null;
        if (canvas) {
            canvas.remove();
        }
        
        // 2. FORCE RE-INITIALIZATION: Rerun particlesJS to create a new canvas.
        window.particlesJS(PARTICLE_CONTAINER_ID, configData); 
        
        // 3. Update cache/state trackers
        particleCache[configName] = true;
        currentParticleConfig = configName;

        // 4. Re-apply pointer-events after a short delay for asynchronous canvas creation
        setTimeout(() => {
            const particlesCanvas = document.querySelector(`#${PARTICLE_CONTAINER_ID} canvas`);
            if (particlesCanvas) {
                particlesCanvas.style.pointerEvents = 'none';
            }
        }, 50); 
    }
}

/**
 * @function updateNavbarActiveState
 * Helper function to manage Navbar active class synchronization.
 */
function updateNavbarActiveState(activeId) {
    document.querySelectorAll('.nav-link').forEach(link => {
        link.classList.remove('active'); 
        if (link.getAttribute('href') && link.getAttribute('href').endsWith(activeId)) {
            link.classList.add('active'); 
        }
    });
}

